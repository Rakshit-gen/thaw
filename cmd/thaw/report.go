// cmdReport turns results/vm.json and results/sim.json into
// results/README.md and an SVG chart per environment. Every number in the
// report is computed here from those files, so the report can't drift from
// what was measured.
func cmdReport(ctx context.Context, args []string) error {
	fs := flag.NewFlagSet("report", flag.ExitOnError)
	dir := fs.String("dir", "results", "directory with vm.json and sim.json")
	fs.Parse(args)

	var v vmFile
	var s simFile
	haveVM := readJSON(filepath.Join(*dir, "vm.json"), &v) == nil
	haveSim := readJSON(filepath.Join(*dir, "sim.json"), &s) == nil
	if !haveVM && !haveSim {
		return fmt.Errorf("no vm.json or sim.json in %s", *dir)
	}
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("# Results\n\nGenerated by `thaw report` from `vm.json` and `sim.json` in this directory. Medians unless marked.\n\n")

	if haveVM {
		w("## Real VMs\n\n%s\n\n%s\n\n", v.Machine, v.Note)
		w("Measured %s. %d training restores, then every strategy on every task of each environment, %s.\n\n",
			strings.Split(v.When, "T")[0], v.Training, strings.Join(v.Profiles, " and "))
		for _, prof := range v.Profiles {
			w("### Store: %s\n\n", prof)
			w("| env | strategy | time to answer | p90 | task in guest, stalls included | waited on (blocks) | fetched | requests | correct |\n|---|---|--:|--:|--:|--:|--:|--:|--:|\n")
			for _, env := range reportEnvs {
				base := v.base(env)
				if base != nil {
					w("| %s | boot + setup from scratch | %s | | | | | | |\n", env, fmtDur(base.BootMs+base.SetupMs))
				}
				for _, st := range reportStrategies {
					rs := v.filter(env, st, prof)
					if len(rs) == 0 {
						continue
					}
					ok, late := 0, 0
					for _, r := range rs {
						if r.OK {
							ok++
						} else if strings.Contains(r.Err, "timeout") || strings.Contains(r.Err, "deadline") {
							late++
						}
					}
					correct := fmt.Sprintf("%d/%d", ok, len(rs))
					if late > 0 {
						correct += fmt.Sprintf(", %d over the 5 min limit", late)
					}
					w("| %s | %s | %s | %s | %s | %.0f | %s | %.0f | %s |\n", env, st,
						fmtDur(med(rs, func(r RunResult) float64 { return r.AnsweredMs })),
						fmtDur(pctl(rs, 0.9, func(r RunResult) float64 { return r.AnsweredMs })),
						fmtDur(med(rs, func(r RunResult) float64 { return r.GuestMs })),
						med(rs, func(r RunResult) float64 { return float64(r.Demand) }),
						mib(int64(med(rs, func(r RunResult) float64 { return float64(r.Bytes) }))),
						med(rs, func(r RunResult) float64 { return float64(r.Requests) }), correct)
				}
			}
			w("\n")
		}
		for _, env := range reportEnvs {
			if svg := v.chart(env, v.Profiles[0]); svg != "" {
				name := fmt.Sprintf("answer-%s.svg", env)
				if err := os.WriteFile(filepath.Join(*dir, name), []byte(svg), 0o644); err != nil {
					return err
				}
				w("![%s](%s)\n\n", env, name)
			}
		}
		if len(v.Forks) > 0 {
			w("### Forks\n\n| env | task | paused | dirty memory | uploaded | fork answered | parent answered |\n|---|---|--:|--:|--:|--:|--:|\n")
			for _, r := range v.Forks {
				f := r.Fork
				fa := "-"
				if f.Restore != nil {
					fa = fmtDur(f.Restore.AnsweredMs)
				}
				w("| %s | %s | %s | %s | %s | %s | %s |\n", r.Env, r.Task, fmtDur(f.PauseMs), mib(int64(f.DirtyMem)*65536), mib(f.Uploaded), fa, fmtDur(r.AnsweredMs))
			}
			w("\n")
		}
	}

	if haveSim {
		w("## Replays\n\n%s\n\n", s.Note)
		for _, sw := range []struct{ name, title string }{
			{"strategy", "Strategies by store tier"},
			{"fetch", "Fetcher settings (s3-express)"},
			{"training", "Traces a plan learned from (s3-express)"},
			{"minfreq", "Share of traces a block needs to be planned (s3-express)"},
			{"blocksize", "Block size (s3-express)"},
		} {
			rows := s.sweep(sw.name)
			if len(rows) == 0 {
				continue
			}
			w("### %s\n\n| env | variant | store | time to answer | recorded on VM | requests | read | recall |\n|---|---|---|--:|--:|--:|--:|--:|\n", sw.title)
			type key struct{ env, variant, prof string }
			groups := map[key][]SimRow{}
			var keys []key
			for _, r := range rows {
				k := key{r.Env, r.Variant, r.Profile}
				if groups[k] == nil {
					keys = append(keys, k)
				}
				groups[k] = append(groups[k], r)
			}
			for _, k := range keys {
				g := groups[k]
				recall := "-"
				if g[0].Planned > 0 || strings.HasPrefix(k.variant, "thaw") {
					recall = fmt.Sprintf("%.0f%%", 100*medSim(g, func(r SimRow) float64 { return r.Recall }))
				}
				w("| %s | %s | %s | %s | %s | %.0f | %s | %s |\n", k.env, k.variant, k.prof,
					fmtDur(medSim(g, func(r SimRow) float64 { return r.Answered })), fmtDur(medSim(g, func(r SimRow) float64 { return r.Baseline })),
					medSim(g, func(r SimRow) float64 { return float64(r.Gets) }), mib(int64(medSim(g, func(r SimRow) float64 { return float64(r.Bytes) }))), recall)
			}
			w("\n")
		}
		if rows := s.sweep("fanout"); len(rows) > 0 {
			w("### Fan-out (s3-express, request cost at S3 Standard prices)\n\n| env | setup | restores | p50 | p95 | GETs | read | cost per 1000 restores |\n|---|---|--:|--:|--:|--:|--:|--:|\n")
			for _, r := range rows {
				w("| %s | %s | %d | %s | %s | %d | %s | $%.4f |\n", r.Env, r.Variant, r.N, fmtDur(r.P50), fmtDur(r.P95), r.Gets, mib(r.Bytes), r.CostPer1000)
			}
			w("\n")
		}
	}
	return os.WriteFile(filepath.Join(*dir, "README.md"), []byte(b.String()), 0o644)
}

var (
	reportEnvs       = []string{"py-data", "repo", "node-ts"}
	reportStrategies = []string{"full", "lazy", "hydrate", "thaw", "thaw+repack"}
)

// The report reads results without the linux-only types, so it has its
// own copies of what it needs.
type vmFile struct {
	When     string       `json:"when"`
	Machine  string       `json:"machine"`
	Note     string       `json:"note"`
	Profiles []string     `json:"profiles"`
	Bases    []reportBase `json:"bases"`
	Runs     []RunResult  `json:"runs"`
	Forks    []RunResult  `json:"forks"`
	Training int          `json:"training_traces"`
}

type reportBase struct {
	Env     string  `json:"env"`
	BootMs  float64 `json:"boot_ms"`
	SetupMs float64 `json:"setup_ms"`
}

type simFile struct {
	Note string   `json:"note"`
	Rows []SimRow `json:"rows"`
}

func (v *vmFile) base(env string) *reportBase {
	for i := range v.Bases {
		if v.Bases[i].Env == env {
			return &v.Bases[i]
		}
	}
	return nil
}

func (v *vmFile) filter(env, st, prof string) []RunResult {
	var out []RunResult
	for _, r := range v.Runs {
		if r.Env == env && r.Strategy == st && r.Profile == prof {
			out = append(out, r)
		}
	}
	return out
}

func (s *simFile) sweep(name string) []SimRow {
	var out []SimRow
	for _, r := range s.Rows {
		if r.Sweep == name {
			out = append(out, r)
		}
	}
	return out
}

// chart draws median time to answer per strategy as horizontal bars.
func (v *vmFile) chart(env, prof string) string {
	type bar struct {
		label string
		ms    float64
		thaw  bool
	}
	var bars []bar
	for _, st := range reportStrategies {
		if rs := v.filter(env, st, prof); len(rs) > 0 {
			bars = append(bars, bar{st, med(rs, func(r RunResult) float64 { return r.AnsweredMs }), strings.HasPrefix(st, "thaw")})
		}
	}
	if len(bars) == 0 {
		return ""
	}
	max := 0.0
	for _, b := range bars {
		max = math.Max(max, b.ms)
	}
	const W, row, left, plot = 560, 26, 110, 360
	h := len(bars)*row + 40
	var sb strings.Builder
	fmt.Fprintf(&sb, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" font-family="ui-monospace, monospace" font-size="12">`, W, h)
	fmt.Fprintf(&sb, `<rect width="%d" height="%d" fill="#f2ede3"/>`, W, h)
	fmt.Fprintf(&sb, `<text x="0" y="16" fill="#17202b" font-size="13">%s, time to first answer (%s, median)</text>`, env, prof)
	for i, b := range bars {
		y := 30 + i*row
		w := math.Max(1, b.ms/max*plot)
		fill := "#7d828b"
		if b.thaw {
			fill = "#6f9a72"
		}
		fmt.Fprintf(&sb, `<text x="0" y="%d" fill="#4a5260">%s</text>`, y+14, b.label)
		fmt.Fprintf(&sb, `<rect x="%d" y="%d" width="%.1f" height="16" fill="%s"/>`, left, y+2, w, fill)
		fmt.Fprintf(&sb, `<text x="%.1f" y="%d" fill="#17202b">%s</text>`, float64(left)+w+6, y+14, fmtDur(b.ms))
	}
	sb.WriteString(`</svg>`)
	return sb.String()
}

func readJSON(path string, v any) error {
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	return json.Unmarshal(b, v)
}

func med(rs []RunResult, f func(RunResult) float64) float64 { return pctl(rs, 0.5, f) }

func pctl(rs []RunResult, p float64, f func(RunResult) float64) float64 {
	xs := make([]float64, len(rs))
	for i, r := range rs {
		xs[i] = f(r)
	}
	return quantile(xs, p)
}

func medSim(rs []SimRow, f func(SimRow) float64) float64 {
	xs := make([]float64, len(rs))
	for i, r := range rs {
		xs[i] = f(r)
	}
	return quantile(xs, 0.5)
}

func quantile(xs []float64, p float64) float64 {
	if len(xs) == 0 {
		return math.NaN()
	}
	sort.Float64s(xs)
	if p == 0.5 && len(xs)%2 == 0 {
		return (xs[len(xs)/2-1] + xs[len(xs)/2]) / 2
	}
	return xs[min(len(xs)-1, int(float64(len(xs)-1)*p+0.5))]
}

func fmtDur(ms float64) string {
	switch {
	case math.IsNaN(ms):
		return "-"
	case ms >= 10000:
		return fmt.Sprintf("%.1f s", ms/1000)
	case ms >= 1000:
		return fmt.Sprintf("%.2f s", ms/1000)
	}
	return fmt.Sprintf("%.0f ms", ms)
}
